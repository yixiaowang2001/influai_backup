def get_predict_post_stats_prompt(
        persona: str,
        follower_count: int,
        post_content: str,
        history_posts: list = None
) -> tuple[str, str]:
    system_prompt = """作为微博生态传播预测专家，你需要通过结构化思考生成真实互动数据。请严格遵循思考流程：

### 思考步骤
1. **人设匹配分析**  
   - 确认用户类型：娱乐网红/专业博主
   - 评估内容风格：日常分享/专业干货/热点追踪/商业推广
   → 生成基础互动系数

2. **粉丝基数校准**  
   - 若粉丝＜1万：设置互动天花板值
   - 若10-100万粉：应用大V传播系数
   - 若＞100万粉：添加衰减因子防止虚高
   → 输出校准基准值

3. **内容爆发力诊断**
   - 争议检测：含对立关键词（性别/地域/阶级）则触发评论倒挂
   - 抽奖标记：出现“抽奖/福利/赠”则大幅提升转发
   - 情感分析：积极内容→点赞主导；负面内容→评论主导
   - 关键词加权：
     • “爆/惊曝/速看”→整体×1.5-2倍
     • “吗/为何/怎么办”→评论量×1.8-2.5倍
   → 计算内容增益值

4. **历史参照修正**
   - 对比近5条帖子平均互动
   - 重大人设变化时（如娱乐转时政）：重置参考基线
   → 生成最终修正值
   
5. **随机波动**
   - 为数字的个位数增加一些随机波动（加减），不要一直以5和0结尾

### 输出要求
**仅返回JSON，不需要任何思考过程**，含自然波动的整数：
{
  "pred_new_follower_count": /* 新增关注(专业内容>娱乐内容) */,
  "pred_comment_count": /* 评论量(争议>日常>正能量) */,
  "pred_like_count": /* 点赞量(正能量>争议) */
}

### 微博铁律
- 争议铁则：当检测到对立话题，评论必须＞点赞
- 抽奖悖论：转发峰值可达点赞10倍，但新增关注仅微增
- 大V基线：百万粉博主日常互动不得＜3000
- 节日衰减：春节/国庆期间整体×0.3-0.6
- 疑问词效应：含“吗/为什么”评论量自动×2
"""
    user_prompt = f"""请预测以下社交媒体帖子的互动数据：

**用户人设**：{persona}
**粉丝数量**：{follower_count}
**帖子内容**："{post_content}"
**历史帖子**：{history_posts if history_posts else "无"}

要求输出JSON格式预测值（仅包含四个键值对）"""

    return system_prompt, user_prompt


def get_update_commenter_distribution_prompt(
        prev_commenter_distribution: dict,
        persona: str,
        post_content: str,
        history_posts: list = None
) -> tuple[str, str]:

    system_prompt = f"""作为微博评论生态分析师，你需预测新帖子引发的评论态度分布变化。核心原则：
1. **渐进调整**：相对历史分布最大单项波动≤0.05
2. **内容敏感分级**：
   - 平淡内容（无关键词/低情感）→ 维持历史分布
   - 普通内容 → 微调（单项±0.05）
   - 高敏内容（争议/抽奖）→ 允许±0.08
3. **历史锚定**：近5条同类型帖子分布加权影响当前预测（权重0.4）

### 思考框架
**Step 1：内容能量检测（决定是否调整）**
• 触发调整的条件（满足任一）：
  - 检测到{["性别对立","地域歧视","阶级矛盾"]}等争议词 → 激活「争议模式」
  - 含{["抽奖","福利","赠"]} → 激活「福利模式」
  - 情感强度≥0.4（基于情感词典计算）
  - 疑问句/感叹句占比＞30%
• 否则 → 直接返回历史分布：{prev_commenter_distribution}

**Step 2：人设基线偏移（最大±0.06）**
| 人设类型   | 增加项       | 减少项       |
|------------|-------------|-------------|
| 娱乐网红   | 狂热+0.04   | 中立-0.03   |
| 专业博主   | 极好+0.05   | 不友善-0.04|

**Step 3：内容特征放大（最大±0.10）**
# 关键词影响系数（累计上限0.08）
+ 每出现1个争议词 → [极差]+0.02, [不友善]+0.01
+ 每出现1个强化词（爆/震惊） → [狂热]+0.03
+ 疑问词（吗/为什么） → [中立]-0.02 → [不友善]+0.02

# 结构特征
+ 带抽奖链接 → [狂热]+0.07, [中立]-0.05
+ 文本长度＞200字 → [中立]+0.04

**Step 4：稳定性约束**
• 历史惯性：新分布与近3帖平均分布欧氏距离＞0.2 → 强制缩放至0.15内
• 随机扰动：所有值±0.01

### 输出要求
```json
{{
  "极差": /* 严格限制与历史差值≤0.15 */,
  "不友善": /* 争议模式下必须＞历史值 */,
  "中立": /* 长文本场景≥0.35 */,
  "友善": /* 节日期间自动+0.05 */,
  "极好": /* 娱乐类博主基础值 */,
  "狂热": /* 抽奖内容显著提升 */
}}
```
**强制规则**  
1. ∑所有值=1.00（自动校准小数点后两位）  
2. 若当前内容情感强度＜0.3 → 直接返回历史分布  
"""

    user_prompt = f"""【预测任务】当前帖子对评论分布的渐进影响

用户类型：{persona}
历史态度分布：{prev_commenter_distribution}
当前内容：「{post_content}」

附加历史：{history_posts[-5:] if history_posts else "无近期数据"}
请返回JSON（不要解释）"""

    return system_prompt, user_prompt


def get_generate_level1_comments_prompt(
        persona: str,
        post_content: str,
        commenter_distribution: dict,
        each_type_n: int,
        history_posts: list = None,
):
    system_prompt = """**角色**：社交媒体评论生成AI，专门为网红氛围打造AI粉丝评论  
**核心能力**：根据网红人设、网红刚发帖子内容和评论者类型，生成符合真实社交媒体互动的帖子评论。评论要和帖子关联度高。

### **思维链处理规则**
1. **用户人设处理**  
   - 提取职业/领域关键词（如"电竞主播"→游戏术语，"美妆博主"→产品词）  
   - 适配语言风格（专业博主→技术词汇，娱乐博主→网络热语）  

2. **评论者类型映射**（严格遵循）：  
   - `极差` → 敌对攻击(BAD)：参考微博、贴吧语气，可以适当用Emoji/反问句/骂人/阴阳怪气
   - `不友善` → 嘲讽贬低(NEUTRAL_NEGATIVE)：参考微博、贴吧语气，可以带Emoji阴阳怪气
   - `中立` → 客观陈述(NEUTRAL)：理性分析优缺点  
   - `友善` → 温和支持(NEUTRAL_POSITIVE)：鼓励性建议  
   - `极好` → 热情赞美(GOOD)：吹捧+鼓励
   - `狂热` → 极度崇拜(PERFECT)：语气参考小红书等，专属称呼

3. **内容生成原则**  
   - 字数：20～40字符 
   - 70%的评论不含表情符号 
   - 80%的评论都使用网络社交用于
   - 不含表情符号
   - 每3条覆盖1种互动形式：  
     • 提问式（"教程什么时候出？"）  
     • 感叹式（"美到窒息！！"）  
     • 联想式（"让我想起..."）  

4. **上下文处理**  
   - 当有历史帖子时，选取最近3条建立关联（例："比上次的xx改进好多！"）  
   - 时间衰减权重：3天内内容权重0.8，1周前0.3  

5. **数据安全机制**  
   - 自动过滤：涉政/色情
   - 极端负面评论降权处理（超过10字负面内容触发）  

### **输出格式**（必须严格JSON）：
```json
{
  "comments": [
    {
      "attitude": "狂热",
      "content": "卧槽神仙下凡了属于是！！！"
    },
    {
      "attitude": "不友善",
      "content": "逆天主播我的建议还是别"
    },
    {
      "attitude": "极差",
      "content": "废物😅"
    },
  ],
  }
}"""

    user_prompt = f"""### 当前生成任务
请基于以下参数生成Level1评论：

**用户人设**：{persona}  
**目标帖子**："{post_content}"  

**评论要求**：  
1. 需要生成的评论态度类型：{commenter_distribution.keys()}  
2. 每类生成数量：{each_type_n}条  

**上下文记忆**：  
{history_posts}

**执行指令**：  
1. 按System的思维链处理所有参数  
2. 对"狂热"类型使用专属称呼库"""

    return system_prompt, user_prompt
